import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bufferCenterline } from "../packages/core/src/geo/buffer.ts";
import { polylineLengthMeters } from "../packages/core/src/geo/measure.ts";
import type { LngLat } from "../packages/core/src/geo/types.ts";
import { TRACK_H3_RESOLUTION, cellsForPolygon } from "../packages/core/src/zones/cells.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const zoneDir = join(root, "supabase/seed/zones");
const centerline = JSON.parse(
  readFileSync(join(zoneDir, "jumeirah-kite.centerline.json"), "utf8"),
) as LngLat[];

const bufferMeters = 25;
const polygon = bufferCenterline(centerline, bufferMeters);
const cells = cellsForPolygon(polygon, TRACK_H3_RESOLUTION);
const lengthMeters = polylineLengthMeters(centerline);

const geojson = {
  type: "FeatureCollection",
  features: [
    {
      type: "Feature",
      properties: {
        role: "centerline",
        name: "Jumeirah Corniche Running Track",
        approximate: true,
        source: "OpenStreetMap way 332925290",
        osm: "https://www.openstreetmap.org/way/332925290",
        note: "Approximate. Traced from the public OSM running track (tartan, sport=running), not a survey. North end is the end of that way near Jumeirah 3; Kite Beach sits on the line; the south end is Umm Suqeim by the Burj Al Arab. Augusto must approve it with a real run.",
      },
      geometry: { type: "LineString", coordinates: centerline },
    },
    {
      type: "Feature",
      properties: {
        role: "polygon",
        slug: "jumeirah-kite",
        approximate: true,
        bufferMeters,
        h3Resolution: TRACK_H3_RESOLUTION,
        containment: "overlapping",
        cellCount: cells.length,
        lengthMeters: Math.round(lengthMeters),
        note: "25 m each side of the centerline, so the parallel cycle path is outside wherever it separates by more than that. Regenerated by scripts/create-zone.ts.",
      },
      geometry: polygon,
    },
  ],
};

const cellsFile = {
  slug: "jumeirah-kite",
  h3Resolution: TRACK_H3_RESOLUTION,
  containment: "overlapping",
  count: cells.length,
  cells,
};

const geojsonText = `${JSON.stringify(geojson, null, 2)}\n`;
writeFileSync(join(zoneDir, "jumeirah-kite.geojson"), geojsonText);
// Same bytes with a .json extension so Next and Vitest can import it.
// jumeirah-kite.geojson stays the seed artifact from ARQUITECTURA §7.2.
writeFileSync(join(zoneDir, "jumeirah-kite.json"), geojsonText);
writeFileSync(join(zoneDir, "jumeirah-kite.cells.json"), `${JSON.stringify(cellsFile, null, 2)}\n`);

console.log(
  `jumeirah-kite: ${cells.length} cells at H3 ${TRACK_H3_RESOLUTION}, centerline ${Math.round(lengthMeters)} m, buffer ${bufferMeters} m`,
);
